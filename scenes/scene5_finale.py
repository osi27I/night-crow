class Marcellus:

    def __init__(self, scene, ch):
        self.S = scene
        self.ch = ch
        self.max_hp = 22.0
        self.hp = 22.0
        self.state = 'idle'
        self.t = 0.0
        self.cd = 1.4
        self.phase = 1
        self.alive = True
        self.blind_t = 0.0
        self.dir = (0.0, 1.0)
        self.combo = 0
        self.hit_done = False
        self.summon_cb = None

    @property
    def x(self):
        return self.ch.root.x

    @property
    def z(self):
        return self.ch.root.z

    @property
    def vulnerable(self):
        return self.state in ('recover', 'blind') or self.blind_t > 0

    def shield_up(self):
        return self.state in ('idle', 'approach') and self.blind_t <= 0

    def wind_time(self):
        return (0.9, 0.72, 0.55)[self.phase - 1]

    def update(self, dt):
        S = self.S
        if not self.alive or S.phase != 'fight':
            return
        p = S.player
        self.t += dt
        self.cd = max(0.0, self.cd - dt)
        ch = self.ch
        if S.abil.in_cloud(self.x, self.z):
            if self.blind_t <= 0:
                S.fx.sparks((self.x, 2.6, self.z), 6, color0=(0.8, 0.8, 0.95, 1.0), color1=(0.5, 0.5, 0.7, 0.0))
            self.blind_t = 0.9
        if self.blind_t > 0:
            self.blind_t -= dt
            if self.state in ('windup', 'charge_wind', 'charge'):
                S.hide_telegraphs()
            if self.state != 'blind':
                self.state, self.t = ('blind', 0.0)
            ch.amount += (0.35 - ch.amount) * min(1.0, 6 * dt)
            a = math.sin(self.t * 2.7) * 1.2
            self._move(math.sin(self.t * 1.3) * 0.6, math.cos(self.t * 0.9) * 0.6, dt, 0.8)
            ch.root.rotation_y += a
            return
        if self.state == 'blind':
            self.state, self.t, self.cd = ('approach', 0.0, 0.7)
        dx, dz = (p.x - self.x, p.z - self.z)
        d = math.hypot(dx, dz)
        st = self.state
        if st in ('idle', 'approach'):
            self.state = 'approach'
            ch.face(dx, dz, dt, turn_speed=7.0)
            self.dir = (dx / max(d, 0.0001), dz / max(d, 0.0001))
            speed = (2.2, 2.7, 3.2)[self.phase - 1]
            if d > 2.2:
                self._move(dx / d, dz / d, dt, speed)
                ch.amount += (0.85 - ch.amount) * min(1.0, 8 * dt)
            else:
                self._move(-dz / d, dx / d, dt, 1.0)
                ch.amount += (0.4 - ch.amount) * min(1.0, 8 * dt)
            if self.cd <= 0:
                if d <= 3.2:
                    self._begin('windup')
                elif d > 5.5 and random.random() < 0.6:
                    self._begin('charge_wind')
                else:
                    self.cd = 0.4
        elif st == 'windup':
            ch.amount *= 0.8
            T = self.wind_time()
            if self.t < T * 0.55:
                ch.face(dx, dz, dt, turn_speed=4.0)
                self.dir = (dx / max(d, 0.0001), dz / max(d, 0.0001))
            ch.arm_r_goal = -150.0 * min(1.0, self.t / (T * 0.7))
            k = min(1.0, self.t / T)
            S.show_ring(self.x + self.dir[0] * 1.5, self.z + self.dir[1] * 1.5, 2.5 * (0.35 + 0.65 * k), 0.25 + 0.55 * k)
            if self.t >= T:
                self._strike()
        elif st == 'recover':
            ch.amount *= 0.8
            ch.arm_r_goal = None
            ch.face(dx, dz, dt, turn_speed=2.0)
            if self.t >= self._recover_time:
                if self.phase == 3 and self.combo == 0:
                    self.combo = 1
                    self._begin('windup')
                else:
                    self.combo = 0
                    self.state, self.t, self.cd = ('approach', 0.0, (1.0, 0.7, 0.4)[self.phase - 1])
        elif st == 'charge_wind':
            T = self.wind_time() + 0.2
            if self.t < T * 0.6:
                ch.face(dx, dz, dt, turn_speed=6.0)
                self.dir = (dx / max(d, 0.0001), dz / max(d, 0.0001))
            ch.amount *= 0.8
            k = min(1.0, self.t / T)
            S.show_lane(self.x, self.z, self.dir, 9.0, 0.2 + 0.6 * k)
            if self.t >= T:
                self.state, self.t, self.hit_done = ('charge', 0.0, False)
                S.hide_telegraphs()
                S.game.audio.play('wingbeat', 0.8, pitch=0.6)
        elif st == 'charge':
            ch.amount = 1.0
            sp = 20.0
            self._move(self.dir[0], self.dir[1], dt, sp, solid=True)
            ch.face(self.dir[0], self.dir[1], dt, turn_speed=30)
            if not self.hit_done and math.hypot(p.x - self.x, p.z - self.z) < 1.35:
                self.hit_done = True
                S.hurt_player(2, (self.x, self.z))
            if self.t >= 0.5 or not S.in_arena(self.x + self.dir[0] * 0.8, self.z + self.dir[1] * 0.8):
                self._recover(1.5)
                S.fx.dust_puff((self.x, 0.2, self.z), 9)
                S.cam.shake(0.2, 0.3)
                S.game.audio.play('thud', 0.9)
        elif st == 'summon':
            ch.amount *= 0.8
            if self.t >= 1.6:
                self.state, self.t, self.cd = ('approach', 0.0, 0.8)

    def _move(self, dx, dz, dt, speed, solid=True):
        S = self.S
        nx, nz = (self.x + dx * speed * dt, self.z + dz * speed * dt)
        x0, x1, z0, z1 = ARENA
        nx, nz = (min(max(nx, x0), x1), min(max(nz, z0), z1))
        if solid:
            nx, nz = S.world.resolve(nx, nz, 0.7)
        self.ch.root.x, self.ch.root.z = (nx, nz)

    def _begin(self, st):
        self.state, self.t = (st, 0.0)
        self.ch.amount = 0.0
        if st == 'windup':
            self.S.game.audio.play('blade', 0.45, pitch=0.55)

    def _strike(self):
        S = self.S
        p = S.player
        self.ch.attack()
        self.ch.arm_r_goal = None
        S.hide_telegraphs()
        S.game.audio.play('blade', 1.0, pitch=0.7)
        cx, cz = (self.x + self.dir[0] * 1.5, self.z + self.dir[1] * 1.5)
        S.ring_fx((cx, cz), (1.0, 0.45, 0.3), 5.2, 0.35, y=0.12)
        S.fx.sparks((cx, 1.0, cz), 12, color0=(1.0, 0.7, 0.3, 1.0), color1=(1.0, 0.2, 0.0, 0.0))
        S.cam.shake(0.12, 0.2)
        if math.hypot(p.x - cx, p.z - cz) < 2.5:
            S.hurt_player(1, (self.x, self.z))
        self._recover((0.95, 0.8, 0.55)[self.phase - 1])

    def _recover(self, dur):
        self.state, self.t = ('recover', 0.0)
        self._recover_time = dur
        self.ch.amount = 0.0

    def staggered_by_hit(self):
        if self.state == 'windup':
            self.t = max(0.0, self.t - 0.25)

    def take_hit(self, dmg, from_xz, kind='dagger'):
        S = self.S
        if not self.alive or self.state == 'summon':
            return False
        ax = math.degrees(math.atan2(from_xz[0] - self.x, from_xz[1] - self.z))
        facing = self.ch.angle
        diff = abs((ax - facing + 180.0) % 360.0 - 180.0)
        front, behind = (diff < 70.0, diff > 110.0)
        if self.shield_up() and front:
            S.game.audio.play('clink', 0.9, pitch=0.9)
            S.fx.sparks((self.x + math.sin(math.radians(facing)) * 0.8, 1.4, self.z + math.cos(math.radians(facing)) * 0.8), 8, color0=(1.0, 0.95, 0.7, 1.0), color1=(1.0, 0.6, 0.2, 0.0))
            S.game.hud.hint('He holds his shield up! Dodge round him, or wait until he swings.', hold=2.6)
            return False
        if self.vulnerable:
            dmg *= 2.0
        elif behind:
            dmg *= 1.5
        self.hp = max(0.0, self.hp - dmg)
        S.on_boss_hit(self, dmg)
        self.staggered_by_hit()
        if self.hp <= 0:
            self.alive = False
            S.on_boss_down()
        else:
            if self.hp <= self.max_hp * 2 / 3 and self.phase < 2:
                self.phase = 2
                self._phase_change('Guards! Seize the crow!')
            if self.hp <= self.max_hp / 3 and self.phase < 3:
                self.phase = 3
                self._phase_change('Enough! I will cut you in two!')
        return True

    def _phase_change(self, shout):
        S = self.S
        self.state, self.t = ('summon', 0.0)
        S.hide_telegraphs()
        S.boss_checkpoint = self.hp
        S.game.hud.caption(shout, hold=1.4, fade=0.4, size=1.9, tone=(1.0, 0.7, 0.5))
        S.game.audio.play('alert', 0.9)
        S.game.post.flash((1.0, 0.3, 0.2), 0.45, 2.0)
        S.cam.shake(0.25, 0.5)
        if self.phase == 2:
            S.spawn_minions(2)
        else:
            S.spawn_minions(1)
            S.game.post.tween(1.0, tint=(1.15, 0.85, 0.82), vignette=0.7)

class Minion:

    def __init__(self, scene, pos):
        self.S = scene
        self.ch = scene.add_char(pos, **LEGION)
        self.alive = True
        self.state = 'chase'
        self.t = 0.0
        self.cd = 1.0
        self.hit_done = False

    @property
    def x(self):
        return self.ch.root.x

    @property
    def z(self):
        return self.ch.root.z

    def update(self, dt):
        S = self.S
        if not self.alive or S.phase != 'fight':
            return
        p = S.player
        dx, dz = (p.x - self.x, p.z - self.z)
        d = math.hypot(dx, dz)
        self.cd = max(0.0, self.cd - dt)
        if S.abil.in_cloud(self.x, self.z):
            self.ch.amount *= 0.9
            return
        if self.state == 'chase':
            self.ch.face(dx, dz, dt, turn_speed=9.0)
            if d > 1.6:
                nx, nz = (self.x + dx / d * 2.9 * dt, self.z + dz / d * 2.9 * dt)
                nx, nz = S.world.resolve(nx, nz, 0.5)
                self.ch.root.x, self.ch.root.z = (nx, nz)
                self.ch.amount += (0.9 - self.ch.amount) * min(1.0, 8 * dt)
            else:
                self.ch.amount *= 0.8
                if self.cd <= 0:
                    self.state, self.t, self.hit_done = ('wind', 0.0, False)
        elif self.state == 'wind':
            self.t += dt
            self.ch.amount *= 0.8
            S.show_ring(self.x + math.sin(math.radians(self.ch.angle)) * 1.0, self.z + math.cos(math.radians(self.ch.angle)) * 1.0, 1.7 * min(1.0, self.t / 0.7), 0.5, slot=1)
            if self.t >= 0.7:
                self.ch.attack()
                S.hide_ring(1)
                S.game.audio.play('blade', 0.6, pitch=0.9)
                if math.hypot(p.x - self.x, p.z - self.z) < 2.0:
                    S.hurt_player(1, (self.x, self.z))
                self.state, self.cd = ('chase', 1.5)

    def die(self):
        if not self.alive:
            return
        self.alive = False
        self.ch.set_pose('fall')
        self.ch.hide_shadow()
        self.S.hide_ring(1)
        self.S.game.audio.play('thud', 0.8)
        self.S.fx.dust_puff((self.x, 0.2, self.z), 7)
        self.S.fx.sparks((self.x, 1.2, self.z), 8, color0=(0.8, 0.9, 1.0, 1.0), color1=(0.4, 0.5, 0.9, 0.0))
