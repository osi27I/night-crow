    def fight_attack(self):
        if self.atk_cd > 0 or self.dodging or self.failing:
            return
        p = self.player
        self.atk_cd = 0.4
        p.ch.attack()
        self.game.audio.play('blade', 0.5, pitch=1.3)
        a = math.radians(p.ch.angle)
        fx, fz = (math.sin(a), math.cos(a))
        for m in self.minions:
            if m.alive:
                dx, dz = (m.x - p.x, m.z - p.z)
                d = math.hypot(dx, dz)
                if d < 2.3 and (dx * fx + dz * fz) / max(d, 0.0001) > 0.45:
                    m.die()
        b = self.boss
        if b.alive:
            dx, dz = (b.x - p.x, b.z - p.z)
            d = math.hypot(dx, dz)
            if d < 2.7 and (dx * fx + dz * fz) / max(d, 0.0001) > 0.35:
                b.take_hit(1.0, (p.x, p.z))

    def fight_knife(self):
        ab = self.abil
        if not ab.can_act() or ab.knife_cd > 0:
            return
        if ab.knives <= 0:
            self.game.hud.hint('No knives left - pick up the bundles at the corners of the hall.', hold=2.5)
            return
        p = self.player
        a = math.radians(p.ch.angle)
        fx, fz = (math.sin(a), math.cos(a))
        best, bd, kind = (None, 99.0, None)
        targets = [(m, 'm') for m in self.minions if m.alive] + ([(self.boss, 'b')] if self.boss.alive else [])
        for t, k in targets:
            vx, vz = (t.x - p.x, t.z - p.z)
            along = vx * fx + vz * fz
            if 0.5 < along < 12.0 and abs(vx * fz - vz * fx) < 1.1 and (along < bd):
                best, bd, kind = (t, along, k)
        ab.knives -= 1
        ab.knife_cd = 0.45
        p.ch.attack()
        self.game.audio.play('blade', 0.45, pitch=1.5)
        if best is None:
            tx, tz, ty = (p.x + fx * 9.0, p.z + fz * 9.0, 1.0)
            cb = lambda: self.game.audio.play('clink', 0.5, pitch=1.6)
        else:
            tx, tz, ty = (best.x, best.z, 1.4)
            cb = (lambda t=best: t.die()) if kind == 'm' else lambda: self.boss.take_hit(1.0, (p.x, p.z), 'knife')
        ab.fire_knife((p.x, 1.3, p.z), (tx, ty, tz), cb)

    def dodge(self):
        p = self.player
        if self.dodge_cd > 0 or self.dodging or self.failing or self.cutscene_active or p.locked:
            return
        self.tl.run(self._dodge())

    def _dodge(self):
        p = self.player
        ch = p.ch
        self.dodging = True
        self.dodge_cd = 0.75
        p.locked = True
        mx = (1 if self._held('d', 'right arrow') else 0) - (1 if self._held('a', 'left arrow') else 0)
        mz = (1 if self._held('w', 'up arrow') else 0) - (1 if self._held('s', 'down arrow') else 0)
        if mx or mz:
            yaw = math.radians(self.cam.yaw)
            fx, fz = (math.sin(yaw), math.cos(yaw))
            rx, rz = (math.cos(yaw), -math.sin(yaw))
            dx, dz = (fx * mz + rx * mx, fz * mz + rz * mx)
            n = math.hypot(dx, dz)
            dx, dz = (dx / n, dz / n)
        else:
            a = math.radians(ch.angle)
            dx, dz = (-math.sin(a), -math.cos(a))
        ch.face(dx, dz)
        self.game.audio.play('wingbeat', 0.5, pitch=1.4)
        self.fx.dust_puff((p.x, 0.1, p.z), 5, color=(0.6, 0.6, 0.7))
        T = 0.3
        t = 0.0
        x0, x1, z0, z1 = ARENA
        while t < T:
            t += self.dt
            k = min(1.0, t / T)
            nx, nz = (p.x + dx * 11.0 * self.dt, p.z + dz * 11.0 * self.dt)
            nx, nz = self.world.resolve(nx, nz, 0.4)
            ch.root.x, ch.root.z = (min(max(nx, x0), x1), min(max(nz, z0), z1))
            ch.root.rotation_x = 360.0 * k
            ch.amount = 1.0
            yield
        ch.root.rotation_x = 0.0
        ch.amount = 0.0
        self.dodging = False
        p.locked = False

