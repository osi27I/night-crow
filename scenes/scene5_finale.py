        g.post.tween(1.2, vignette=0.85, desat=0.35, bloom=1.2, tint=(0.9, 0.95, 1.1))
        yield 1.4
        yield from self.walk(a, b.x, b.z - 1.6, speed=1.8)
        a.face(0, 1)
        yield from self.talk([('Marcellus', '...Who sent you? Which one of them was it?'), ('Abdo', 'Nobody sent me. I was a boy in a village you did not bother to remember.'), ('Marcellus', 'Then you are... nothing. A shadow with a knife.'), ('Abdo', 'A shadow is exactly what Rome will fear.')], {'Abdo': a, 'Marcellus': b.ch})
        a.attack()
        g.audio.play('blade', 1.0)
        g.post.flash((1.0, 1.0, 1.0), 0.8, 2.6)
        self.fx.sparks((b.x, 1.3, b.z), 24, color0=(1.0, 0.95, 0.8, 1.0), color1=(1.0, 0.4, 0.2, 0.0))
