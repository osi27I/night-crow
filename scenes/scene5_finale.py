        a = self.abdo
        b = self.boss
        self.phase = 'kill'
        self._camera_target_override = None
        self.abil.sight_off(cooldown=0.0)
        self.abil.enabled = False
        self.begin_cutscene()
        self.hide_telegraphs()
        self.hide_ring(1)
        for m in self.minions:
            m.die()
        Clock.time_scale = 0.15
        g.post.flash((1.0, 1.0, 1.0), 0.7, 2.2)
        self.cam.shake(0.3, 0.6)
        self.shot((b.x - 3.2, 2.2, b.z - 4.0), (b.x, 1.4, b.z), speed=2.4)
        yield 0.8
