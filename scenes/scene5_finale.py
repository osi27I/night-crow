    def credits(self):
        g = self.game
        g.audio.music('mus_legend', 0.5, fade=1.0)
        rows = []
        y = -0.62
        for text, scale, bold in CREDITS:
            t = Text(text=text, parent=camera.ui, position=(0, y), origin=(0, 0), scale=scale * (1.7 if bold else 1.35), font=FONT_BOLD if bold else FONT, color=color.rgba(0.95, 0.82, 0.5, 1) if bold else color.rgba(0.88, 0.88, 0.92, 1), z=-0.95, add_to_scene_entities=False)
            self.ui.append(t)
            rows.append(t)
            y -= 0.075 if text else 0.05
        speed = 0.058
        while rows[-1].y < 0.62:
            for t in rows:
                t.y += speed * Clock.raw_dt
                al = 1.0 - min(1.0, max(0.0, (abs(t.y) - 0.42) / 0.12))
                t.color = color.rgba(t.color[0], t.color[1], t.color[2], al)
            yield
        yield 1.5
